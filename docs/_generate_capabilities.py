"""Generate the capability matrix and the not-implemented list.

Both are views of one registry and neither is written by hand. A capability
table maintained by editing it is a table that disagrees with the code the
first time somebody raises a level and forgets the page -- which is exactly
what `docs/stability.md` records happening to its own counts before they were
guarded.

Run it, or let `tests/test_docs_capabilities.py` run it: that test regenerates
into a temporary directory and compares, so a stale page is a failing test
rather than a page nobody re-read.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "_generated" / "capabilities.md"

#: What each level means for a reader deciding whether to trust a number.
#: The words are `_rheplicant_bootstrap.capability`'s own; only the audience
#: is different, so they are quoted rather than paraphrased.
MEANING = {
    "maintained": (
        "The implementation is the real physics or the real arithmetic, it is "
        "tested against something independent, and a result through it is a "
        "result."
    ),
    "experimental": (
        "Usable with stated limits and no general validity guarantee. Read the "
        "limits before reading the number."
    ),
    "placeholder": (
        "The CONTRACT is real and tested -- shapes, ordering, purity, PRNG "
        "consumption -- and the NUMBERS are a stand-in. A run through one of "
        "these is not a prediction."
    ),
    "unavailable": (
        "Not implemented on this surface. A document naming it is refused, "
        "with the capability it belongs to."
    ),
}

ORDER = ("maintained", "experimental", "placeholder", "unavailable")


def render() -> str:
    from _rheplicant_bootstrap.capability import REGISTRY, Surface
    from rheplicant.radio import capabilities

    levels = capabilities()
    by_level: dict[str, list[str]] = {}
    for name, maturity in sorted(levels.items()):
        by_level.setdefault(maturity.value, []).append(name)

    lines = [
        "<!-- Generated by docs/_generate_capabilities.py. Do not edit. -->",
        "",
        "## The shipped classes, by level",
        "",
        f"{len(levels)} classes carry a `maturity` of their own. The level is a "
        "ClassVar on the class, so this table is a walk of the package rather "
        "than a list kept beside it.",
        "",
        "| Level | Count | What it means |",
        "|---|---|---|",
    ]
    for level in ORDER:
        names = by_level.get(level, [])
        if not names:
            continue
        lines.append(f"| {level.capitalize()} | {len(names)} | {MEANING[level]} |")
    lines.append("")

    for level in ORDER:
        names = by_level.get(level, [])
        if not names:
            continue
        lines += [f"### {level.capitalize()}", ""]
        lines += [f"- `{name}`" for name in names]
        lines.append("")

    document_rows = [row for row in REGISTRY if row.surface is Surface.DOCUMENT]
    python_rows = [row for row in REGISTRY if row.surface is Surface.PYTHON]

    lines += [
        "## What is not implemented",
        "",
        "A capability that is not a class has no ClassVar to carry a level, so "
        "it is a row in a registry instead: a document key a schema names and "
        "refuses, or an importable surface whose level is not a property of "
        "any single class.",
        "",
        f"### Document keys ({len(document_rows)})",
        "",
        "| Key | Level | What it is |",
        "|---|---|---|",
    ]
    for row in sorted(document_rows, key=lambda row: row.name):
        lines.append(f"| `{row.name}` | {row.maturity.value} | {row.what} |")
    lines += [
        "",
        f"### Importable surfaces ({len(python_rows)})",
        "",
        "| Name | Level | What it is |",
        "|---|---|---|",
    ]
    for row in sorted(python_rows, key=lambda row: row.name):
        lines.append(f"| `{row.name}` | {row.maturity.value} | {row.what} |")
    lines.append("")
    return "\n".join(lines)


def main(destination: pathlib.Path | None = None) -> pathlib.Path:
    target = OUTPUT if destination is None else destination
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(), encoding="utf-8")
    return target


if __name__ == "__main__":
    written = main(pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else None)
    print(f"wrote {written}")
