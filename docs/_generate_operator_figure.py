"""Generate the tour's ``State -> Operator -> State`` schematic, light and dark.

Run MANUALLY, and only when the schematic changes::

    .venv/bin/python docs/_generate_operator_figure.py

Unlike its neighbour ``_generate_tour_figures.py``, nothing here is measured --
this is a diagram, not a result, so there is no code to run and no number to
report. What the script buys is that the two themes come from **one template**:
the geometry cannot drift between ``-light`` and ``-dark``, which is exactly
what happens when a hand-edited SVG pair is tweaked on one side only.

Written by hand rather than through matplotlib or mermaid because both produce
a heavier, blunter object than a schematic this small deserves -- the previous
version was a mermaid ``flowchart LR`` and read as filler.

The palette is the same GitHub Primer set the data figures use, so the diagram
sits in their visual language rather than beside it.
"""

import xml.dom.minidom
from pathlib import Path

STATIC = Path(__file__).parent / "_static"

THEMES = {
    "light": {"fg": "#24292f", "muted": "#57606a", "grid": "#d0d7de",
              "accent": "#0969da", "chip": "#f6f8fa", "opfill": "#ffffff"},
    "dark": {"fg": "#e6edf3", "muted": "#9198a1", "grid": "#30363d",
             "accent": "#58a6ff", "chip": "#161b22", "opfill": "#0d1117"},
}

MONO = "ui-monospace,SFMono-Regular,'SF Mono',Menlo,Consolas,monospace"
SANS = "-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif"

#: The arrow marker gets a per-theme id: both files can end up inlined into one
#: HTML document, and duplicate ``id`` attributes would have the second diagram
#: resolve ``url(#a)`` against the first one's marker.
TEMPLATE = """<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 560 96" \
width="560" height="96" role="img" aria-label="A State goes in, an operator \
returns a new State with data replaced and every other field shared.">
  <!-- Generated by docs/_generate_operator_figure.py; edit that, not this. -->
  <defs>
    <marker id="a{k}" viewBox="0 0 10 10" refX="9" refY="5"
            markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M0,1.2 L9,5 L0,8.8" fill="none" stroke="{muted}"
            stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"/>
    </marker>
  </defs>

  <!-- State in -->
  <rect x="4" y="22" width="146" height="52" rx="10"
        fill="{chip}" stroke="{grid}" stroke-width="1.25"/>
  <text x="77" y="45" text-anchor="middle" font-family="{mono}"
        font-size="15" fill="{fg}">State</text>
  <text x="77" y="61" text-anchor="middle" font-family="{sans}"
        font-size="9" fill="{muted}" letter-spacing="0.15">\
data · coords · env · meta</text>

  <line x1="156" y1="48" x2="196" y2="48" stroke="{muted}"
        stroke-width="1.6" stroke-linecap="round" marker-end="url(#a{k})"/>

  <!-- the operator: the only accented box, because it is the only actor -->
  <rect x="202" y="14" width="156" height="68" rx="12"
        fill="{opfill}" stroke="{accent}" stroke-width="1.75"/>
  <text x="280" y="43" text-anchor="middle" font-family="{mono}"
        font-size="15" fill="{fg}">Operator</text>
  <text x="280" y="60" text-anchor="middle" font-family="{sans}"
        font-size="9" fill="{muted}" letter-spacing="0.15">\
one node of the graph</text>

  <line x1="364" y1="48" x2="404" y2="48" stroke="{muted}"
        stroke-width="1.6" stroke-linecap="round" marker-end="url(#a{k})"/>

  <!-- State out: the SAME fields, and only `data` accented. That is the
       buffer-reference story the tour tells, carried by the picture. -->
  <rect x="410" y="22" width="146" height="52" rx="10"
        fill="{chip}" stroke="{grid}" stroke-width="1.25"/>
  <text x="483" y="45" text-anchor="middle" font-family="{mono}"
        font-size="15" fill="{fg}">State</text>
  <text x="483" y="61" text-anchor="middle" font-family="{sans}"
        font-size="9" letter-spacing="0.15"><tspan fill="{accent}"\
 font-weight="600">data</tspan><tspan fill="{muted}"> · coords · env · meta\
</tspan></text>
</svg>
"""


def main() -> None:
    for name, colours in THEMES.items():
        svg = TEMPLATE.format(k=name[0], mono=MONO, sans=SANS, **colours)

        # An SVG served as image/svg+xml is parsed as XML, and XML forbids "--"
        # inside a comment -- a browser does not warn, it declines to render the
        # image at all. Costly to spot by eye, because the file still looks
        # right in an editor and diffs clean. Caught here instead.
        xml.dom.minidom.parseString(svg)

        out = STATIC / f"tour-operator-{name}.svg"
        out.write_text(svg)
        print(f"wrote {out.relative_to(Path(__file__).parent.parent)}")


if __name__ == "__main__":
    main()
