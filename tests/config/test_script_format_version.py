"""A generated script declares its format, and an unknown one is refused.

A3-6: the embedded script had no format version, no golden and no
old-version refusal. A published script is a file on somebody's disk that
calls back into this package BY KEYWORD, so a script generated by one
rheplicant and run by another either worked by luck or failed somewhere inside
the call with a message about an unexpected argument.

Three things are asserted, and the third is the one that costs a user
something, which is why its wording is pinned too.
"""

from __future__ import annotations

import io
import os

import pytest

from _rheplicant_bootstrap.entry import run_embedded_config
from _rheplicant_bootstrap.errors import ConfigError
from _rheplicant_bootstrap.script import SCRIPT_FORMAT_VERSION, render_script
from _rheplicant_bootstrap.types import SourceInput


def _render() -> str:
    source = SourceInput(
        input_bytes=b"schema_version: 1\n",
        source_path="doc.yaml",
        source_realpath=None,
        source_name="doc.yaml",
        base_dir=os.getcwd(),
        launch_mode="script",
    )
    return render_script(source, ()).decode()


def test_the_rendered_script_declares_the_current_format():
    text = _render()
    assert f"format_version={SCRIPT_FORMAT_VERSION}," in text, (
        "the generated program does not pass format_version, so the entry "
        f"point cannot tell which shape it was written for. Rendered:\n{text}"
    )


def test_a_script_without_a_version_is_refused_and_told_what_to_do():
    """The pre-versioning case, which is every script published before this.

    Refusing is right -- the reader cannot know the shape -- but a refusal
    that only says "no" costs the user their file. The message has to name the
    command that regenerates it and say the embedded bytes are still theirs.
    """
    with pytest.raises(ConfigError) as raised:
        run_embedded_config(
            source_path="doc.yaml",
            source_realpath=None,
            source_name="doc.yaml",
            base_dir=".",
            presets=(),
            input_bytes=b"schema_version: 1\n",
        )
    message = str(raised.value)
    assert "predates" in message, message
    assert "rheplicant script" in message, (
        f"the refusal does not name the command that fixes it: {message}"
    )


@pytest.mark.parametrize(
    "version",
    [
        pytest.param(SCRIPT_FORMAT_VERSION + 1, id="newer"),
        pytest.param(SCRIPT_FORMAT_VERSION - 1, id="older"),
        pytest.param(float(SCRIPT_FORMAT_VERSION), id="float"),
        pytest.param(str(SCRIPT_FORMAT_VERSION), id="str"),
        pytest.param(True, id="bool"),
    ],
)
def test_a_version_that_is_not_the_current_integer_is_refused(version):
    """Including the loosely-equal ones.

    `1.0 != 1` and `True != 1` are both False, so a comparison by `!=` alone
    would accept either and make the call against a shape nothing verified --
    the same defect this package just repaired in four other readers.
    """
    with pytest.raises(ConfigError) as raised:
        run_embedded_config(
            format_version=version,
            source_path="doc.yaml",
            source_realpath=None,
            source_name="doc.yaml",
            base_dir=".",
            presets=(),
            input_bytes=b"schema_version: 1\n",
        )
    assert "script format" in str(raised.value), raised.value


def test_the_current_version_is_not_refused_for_its_version():
    """Anti-vacuity: the checks above must be about the VERSION.

    Passing the right one must get past the version clause. It will fail
    later, on the document, and that is a different sentence -- which is
    exactly what this asserts.
    """
    # `run_embedded_config` RETURNS an exit code for a bad document rather
    # than raising -- measured, the first version of this test asserted a
    # raise and failed with DID NOT RAISE. The version clause is the one that
    # raises; everything past it reports.
    stderr = io.StringIO()
    code = run_embedded_config(
        format_version=SCRIPT_FORMAT_VERSION,
        source_path="doc.yaml",
        source_realpath=None,
        source_name="doc.yaml",
        base_dir=".",
        presets=(),
        input_bytes=b"schema_version: 1\n",
        stderr=stderr,
    )
    assert code != 0, "the fixture document should not run cleanly"
    assert "script format" not in stderr.getvalue(), (
        "the current version is refused as a version, so every test above is "
        f"passing for the wrong reason: {stderr.getvalue()}"
    )
