"""``integrity.json``: one digest that anchors the whole published tree.

WHAT THIS CLOSES, AND WHAT IT DOES NOT
--------------------------------------
Before this file existed, every published artefact was hashed and nothing
hashed the set of them. ``provenance.json`` records a ``sha256`` per content
artefact, but it is itself a *metadata* row, and
:mod:`_rheplicant_bootstrap.audit.provenance` refuses to let a metadata row
carry a digest at all -- ``"metadata cannot claim bytes or a digest."`` The
ownership marker holds ``{format_version, run_directory_id}``, which is a
token saying who owns the directory, not a statement about its contents.

The consequence, measured rather than supposed: a publisher could rewrite a
recorded file *and* the ``sha256`` in the provenance row that names it, and the
result is internally consistent. Nothing in the tree disagrees with anything
else in the tree, because no file's digest depends on any other file's bytes.

This file makes exactly one claim: **here is every published path and its
digest, and here is one digest over that whole list.** A single value -- the
``root_sha256`` -- now stands for the entire tree. Record it somewhere outside
the tree (a lab notebook, a signature, a run database) and the tree becomes
verifiable against an external anchor rather than against itself.

**It does not make the tree tamper-proof, and claiming so would be the kind of
overstatement this package exists to avoid.** An attacker who rewrites a file
must now also rewrite this file, which is one more step, not an impossible one.
What it does make impossible is *partial* tampering and *silent corruption*: a
file edited without its manifest, a truncated copy, a bit flipped in transit, a
product regenerated by a later run. Those are the failures that actually happen
to archived campaigns, and none of them was detectable before.

WHY IT DOES NOT COVER ITSELF
----------------------------
A file cannot contain its own digest. ``integrity.json`` is therefore the one
published path absent from its own manifest, and this is stated in the payload
(``"covers": "every published file except this one"``) rather than left for a
reader to infer from a missing row. A verifier that finds an unlisted file that
is not this one has found an addition, and says so.
"""

from __future__ import annotations

import hashlib
from collections.abc import Mapping, Sequence

from _rheplicant_bootstrap.audit.json import canonical_json_bytes
from _rheplicant_bootstrap.errors import ConfigError

#: The published name. Written into the staged tree beside the metadata files,
#: and replaced with them, because it must be computed after they are final.
INTEGRITY_NAME = "integrity.json"

#: Bumped when the payload's shape changes. A verifier that does not know a
#: version refuses rather than guessing which fields it may ignore.
INTEGRITY_FORMAT_VERSION = 1

_COVERS = "every published file except this one"


def _digest_rows(
    rows: Sequence[tuple[str, bytes]],
) -> tuple[Mapping[str, object], ...]:
    """One record per file, sorted by path so the list is order-independent.

    Sorted, not in write order: the write order is a transaction detail, and
    two trees with identical contents must produce identical bytes here or the
    root digest stops being a property of the contents.
    """
    seen: set[str] = set()
    records = []
    for relative_path, payload in rows:
        if type(relative_path) is not str or type(payload) is not bytes:
            raise ConfigError("integrity rows must be exact text/bytes pairs.")
        if relative_path == INTEGRITY_NAME:
            raise ConfigError(
                f"{INTEGRITY_NAME} cannot appear in its own manifest."
            )
        if relative_path in seen:
            raise ConfigError(f"integrity row {relative_path!r} is duplicated.")
        seen.add(relative_path)
        records.append(
            {
                "relative_path": relative_path,
                "bytes": len(payload),
                "sha256": hashlib.sha256(payload).hexdigest(),
            }
        )
    return tuple(sorted(records, key=lambda row: row["relative_path"]))


def root_digest(rows: Sequence[tuple[str, bytes]]) -> str:
    """The one value that stands for the whole tree.

    Taken over the canonical JSON of the sorted per-file list, not over a
    concatenation of the payloads: a concatenation is ambiguous (two different
    splits of the same bytes hash alike) and says nothing about the paths,
    which is half of what a tree is.
    """
    return hashlib.sha256(canonical_json_bytes(_digest_rows(rows))).hexdigest()


def integrity_bytes(rows: Sequence[tuple[str, bytes]]) -> bytes:
    """The published payload, as canonical JSON with one trailing newline."""
    files = _digest_rows(rows)
    return canonical_json_bytes(
        {
            "format_version": INTEGRITY_FORMAT_VERSION,
            "covers": _COVERS,
            "files": files,
            "root_sha256": hashlib.sha256(canonical_json_bytes(files)).hexdigest(),
        }
    )


def verify_tree(published: Mapping[str, bytes]) -> tuple[str, ...]:
    """Check a published tree against its own ``integrity.json``.

    Args:
        published: every file in the tree by relative path, ``integrity.json``
            included. Read them from disk and pass them here; this function
            does no IO, so it is equally usable on a directory, an archive
            member set, or an object store listing.

    Returns:
        A tuple of human-readable disagreements, empty when the tree verifies.
        A tuple rather than a bool because "which file" is the whole question a
        reader has when a check fails, and a bool throws it away.

    This reports rather than raises: a caller verifying an archive of a hundred
    runs wants the list, not the first exception.
    """
    if not isinstance(published, Mapping):
        raise ConfigError("published tree must be a mapping of path to bytes.")
    payload = published.get(INTEGRITY_NAME)
    if payload is None:
        return (f"{INTEGRITY_NAME} is absent, so the tree has no anchor.",)
    try:
        import json

        manifest = json.loads(payload)
    except Exception:
        return (f"{INTEGRITY_NAME} is not JSON.",)
    if (
        type(manifest) is not dict
        or manifest.get("format_version") != INTEGRITY_FORMAT_VERSION
    ):
        return (
            f"{INTEGRITY_NAME} is not format_version "
            f"{INTEGRITY_FORMAT_VERSION}; this verifier will not guess at "
            "another shape.",
        )

    problems: list[str] = []
    listed = manifest.get("files")
    if type(listed) is not list:
        return (f"{INTEGRITY_NAME} has no file list.",)

    # The manifest must first be self-consistent: a rewritten row with the root
    # left alone is caught here, before any file is read.
    recomputed = hashlib.sha256(canonical_json_bytes(listed)).hexdigest()
    if recomputed != manifest.get("root_sha256"):
        problems.append(
            "root_sha256 does not match the file list it claims to cover -- "
            "the manifest was edited without recomputing its own root."
        )

    expected = {}
    for row in listed:
        if type(row) is not dict or type(row.get("relative_path")) is not str:
            problems.append(f"{INTEGRITY_NAME} has a malformed file row.")
            continue
        expected[row["relative_path"]] = row

    for relative_path, row in sorted(expected.items()):
        actual = published.get(relative_path)
        if actual is None:
            problems.append(f"{relative_path}: listed in the manifest and absent.")
            continue
        digest = hashlib.sha256(actual).hexdigest()
        if digest != row.get("sha256"):
            problems.append(
                f"{relative_path}: sha256 is {digest}, manifest says "
                f"{row.get('sha256')}."
            )
        elif len(actual) != row.get("bytes"):
            problems.append(
                f"{relative_path}: {len(actual)} bytes, manifest says "
                f"{row.get('bytes')}."
            )

    for relative_path in sorted(published):
        if relative_path == INTEGRITY_NAME or relative_path in expected:
            continue
        problems.append(
            f"{relative_path}: present in the tree and absent from the "
            "manifest, so it was added after publication."
        )
    return tuple(problems)
